import type { AutonomousFlowStep, NicheLandingConfig, PainOption } from "./types";

function createIntentPain({
  id,
  chip,
  title,
  description,
  result,
  agentId,
  steps,
  systemCards,
}: {
  id: string;
  chip: string;
  title: string;
  description: string;
  result: string;
  agentId: string;
  steps: AutonomousFlowStep[];
  systemCards: string[];
}): PainOption {
  const lines = steps
    .filter((step): step is Extract<AutonomousFlowStep, { type: "message" }> => step.type === "message")
    .map((step) => ({
      from: step.actor === "student" ? "agent" as const : "owner" as const,
      text: step.text,
    }));

  return {
    id,
    chip,
    title,
    description,
    result,
    conversation: {
      title: "Taliya",
      status: "exemplo ilustrativo",
      lines,
      result,
    },
    autonomousFlow: {
      title: "Taliya",
      status: "exemplo ilustrativo",
      agentId,
      contactName: "Taliya",
      steps,
      systemCards,
      result,
    },
  };
}

